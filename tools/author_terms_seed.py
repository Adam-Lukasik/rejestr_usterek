def tnorm(s):
    s = re.sub(r"[_–—]+", " ", str(s or ""))
    s = re.sub(r"\s+", " ", s).strip()
    return s.casefold()


def main():
    entries = []
    seen = set()

    def emit(form, kind, pl, en, de, sample=""):
        nf = tnorm(form)
        if not nf or nf in seen:
            return
        seen.add(nf)
        entries.append({"form": nf, "kind": kind, "pl": pl, "en": en,
                        "de": de, "sample": sample or form})

    for tok, (pl, en, de) in TOKENS.items():
        emit(tok, "token", pl, en, de)
    for ph, (pl, en, de) in PHRASES.items():
        emit(ph, "phrase", pl, en, de)
    for j in JARGON:
        emit(j, "jargon", j, j, j)

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump({"entries": entries}, f, ensure_ascii=False, indent=1)
    print(f"{len(entries)} entries -> {OUT_PATH}")


if __name__ == "__main__":
    main()
